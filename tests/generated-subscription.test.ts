import { afterEach, describe, expect, it, vi } from "vitest";

import { loadGeneratedSubscriptionUrl } from "../src/app/lib/generated-subscription";

afterEach(() => { vi.restoreAllMocks(); });

function resolveWith(config: Record<string, unknown>, target = "mihomo-config") {
  return vi.spyOn(globalThis, "fetch").mockResolvedValue(Response.json({ config, target }));
}

describe("loadGeneratedSubscriptionUrl", () => {
  it("loads a generated link back into the conversion form", async () => {
    const fetchSpy = resolveWith({
      version: 1,
      name: "个人订阅",
      nodeSettings: {
        addCountryFlag: true,
        excludePattern: "过期",
        includePattern: "US|JP",
        renameRules: [
          { pattern: "USA", replacement: "US" },
          { pattern: "Tokyo", replacement: "JP" },
        ],
        showNodeType: true,
        skipCertVerify: false,
        sortMode: "name-asc",
        tfo: true,
        udp: true,
      },
      rulePreset: "flacier",
      fallbackMode: "mihomo-provider",
      sourceMode: "convert",
      sourceUserAgent: "ClashParty/2.0",
      sources: [
        { name: "订阅 1", type: "subscription", value: "https://provider.example/sub" },
        { name: "节点 1", type: "node", value: "ss://example" },
      ],
      updateIntervalHours: 12,
    });

    await expect(loadGeneratedSubscriptionUrl("https://rules.flacier.com/s/abcdefghijklmnop/mihomo-config")).resolves.toMatchObject({
      excludePattern: "过期",
      includePattern: "US|JP",
      name: "个人订阅",
      allowClientFallback: true,
      renameRules: [
        { pattern: "USA", replacement: "US" },
        { pattern: "Tokyo", replacement: "JP" },
      ],
      rulePreset: "flacier",
      sourceText: "https://provider.example/sub\nss://example",
      sourceUserAgent: "ClashParty/2.0",
      sortMode: "name-asc",
      target: "mihomo-config",
      updateIntervalHours: 12,
    });
    expect(fetchSpy).toHaveBeenCalledWith("/api/subscriptions/resolve", expect.objectContaining({ method: "POST" }));
  });

  it("rejects links that were not generated by this site", async () => {
    await expect(loadGeneratedSubscriptionUrl("https://example.com/sub")).rejects.toThrow("不是本站生成的订阅链接");
  });

  it("uses the compatible subscription user agent for older links", async () => {
    resolveWith({
      version: 1,
      name: "个人订阅",
      nodeSettings: {},
      rulePreset: "flacier",
      sourceMode: "convert",
      sources: [{ name: "节点 1", type: "node", value: "ss://example" }],
      updateIntervalHours: 6,
    });

    await expect(loadGeneratedSubscriptionUrl("https://rules.flacier.com/s/abcdefghijklmnop/mihomo-config"))
      .resolves.toMatchObject({ sourceUserAgent: "clash.meta" });
  });
});
